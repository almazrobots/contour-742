// T-133 (OS-INSP-2.1.15): версия правил сравнения. Как версия ML (OS-INSP-2.1.12) переразбирает файлы, так смена
// правил сравнения пересчитывает проверку по всем параметрам — без повторного разбора. Без этого новое правило
// (OS-INSP-2.2.21: значение только из профильной марки) не дошло бы до уже посчитанной проверки: пересчёт трогает
// только параметры новых файлов, и ложный кандидат М-059 «Алтуфьево» остался бы на экране.
// Поднимать при каждом изменении правил сравнения или выбора источников; в версии — правило, которое её сменило.

export const RULES_VERSION = "2026-09-28 OS-INSP-2.2.21 OS-INSP-2.2.4 OS-INSP-3.1.25 OS-INSP-3.1.70"; // 3.1.70 — слой L8 после оператора (T-177); 3.1.25 — М-072 по классу давления PN (T-135)

/** Пересчитать все параметры: первый расчёт или проверка посчитана другими правилами (NULL — до учёта версии). */
export const recomputeAllParams = (first: boolean, stored: string | null | undefined): boolean => first || stored !== RULES_VERSION;
