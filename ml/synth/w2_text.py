"""Строки ТЭП синтетического объекта «132 параметра» для паспортов количества W2 текстового пути (T-191).

Система читает эти параметры по паспорту (data/seed/passports/M-0NN.json): подпись строки должна находиться оборотом
паспорта, а значение — быть числом. Генератор v3 пишет подписью самый короткий якорь Матрицы, а для правила «равно»
у строки — словесную пару («исполнение 1/2»); здесь — подписи под обороты и числовой генератор, «хуже» которого идёт в
сторону правила паспорта. Общий пул фабрики не меняется: запись собирается заново для каждого объекта.
"""

from __future__ import annotations

from synth import factory as F
from synth import factory_v3 as V3

LABELS = {
    "M-024": "Объём выемки грунта",
    "M-045": "Уклон кровли",
    "M-086": "Максимальная численность работающих",
    "M-088": "Мощность временного электроснабжения",
    "M-093": "Объём демонтируемых конструкций",
    "M-094": "Масса образующихся отходов",
    "M-126": "Теплопроводность утеплителя стен",
    "M-127": "Приведённое сопротивление теплопередаче окон",
}
# параметр с паспортом количества, у которого v3 пишет словесную пару: М-127 — Ro окон, хуже — уменьшение
NUMERIC = {"M-127": "decrease"}


def active() -> dict[str, str]:
    """Подписи только для паспортов, принятых в data/seed/passports: паспорт из draft/ (без цифр отложенного набора)
    загрузчик не читает, параметр идёт лексическим путём по якорю Матрицы — подпись v3 ему и нужна."""
    return {c: lbl for c, lbl in LABELS.items() if (F.ROOT / "data/seed/passports" / f"{c}.json").exists()}


def entry(code: str, label: str) -> dict:
    """Запись пула фабрики для объекта: подпись label; для NUMERIC — числовой генератор по правилу паспорта."""
    e = {**F.POOL[code], "label": label}
    if code in NUMERIC:
        e.update(V3.number_entry({**F.MATRIX[code], "data_type": "number", "compare": {"kind": NUMERIC[code]}}))
    return e
