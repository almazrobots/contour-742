"""Паспортные формы синтетики W3 (T-210): параметр с паспортом вида пишется так, как его пишут в реальных ПЗ, АР, СПЗУ, ПОД.

Фабрика v3 для строкового параметра без ручного генератора рисует условную форму: пары «предусмотрено / не
предусмотрено», «вариант А / вариант Б» (text_entry) или «<число> по проекту» (string_numeric_entry). Паспортный
экстрактор W3 такое законно не читает — в документах так не пишут, — и система честно ставит MISSING_EVIDENCE там, где
эталон ждёт сверку. Здесь — формы, которые экстрактор паспорта читает как реальный документ (экстрактор под
генератор не подгоняется):

- М-043, М-106 (direction_mentions): «Двери эвакуационных выходов открываются по направлению выхода из здания»,
  хуже — «… открываются внутрь помещения» (СП 1.13130.2020, п. 4.2.6);
- М-033 (quantity_mentions, ‰): «Продольный уклон проездов 20 ‰»; хуже — изменение больше допуска паспорта (0,5 ‰)
  в пределах норм 4–80 ‰: изменение в РД/ИД само по себе нарушение (CMP-18);
- М-048 (quantity_mentions, ступени): «проступь 300 мм; подступенок 150 мм; 12 ступеней в марше»; проступь первой —
  её сравнивает Матрица (min 300 по главному числу строки, OS-INSP-2.2.9); база — проступь ≥ 300 и подступенок ≤ 150
  (рекомендации Матрицы выполнены), хуже — проступь < 250 (норма СП, CANDIDATE), а не 250–300 (только гипотеза);
- T-212 (presence_mentions): «Демпферные ленты в сопряжениях перегородок предусмотрены», хуже — «не предусмотрены
  (исключены)»; М-070 — со счётом заземлителей (правило Матрицы «уменьшение»: хуже — меньше заземлителей);
  М-091 (method) — метод демонтажа по словарю паспорта, хуже — метод без родства с ПД (CHANGED).

Форма включается, только если паспорт параметра есть в data/seed/passports и его value.kind — тот, под который форма
написана: до влития паспорта (T-212) параметр рисуется прежней формой, эталон и выбор нарушений не меняются.
График и перечень ИД (М-082, 087, 096, T-213) — таблица из нескольких строк, её генератор не рисует: переходный список
usability_132_pending.json.
"""

from __future__ import annotations

import json
from functools import cache

from synth import factory as F

OUTWARD = ("по направлению выхода из здания", "наружу", "по направлению эвакуации")
INWARD = ("внутрь помещения", "против направления эвакуации")


def _direction(label: str) -> dict:
    """Направление открывания: значение — (сторона, вариант формулировки); 0 — наружу, 1 — внутрь."""
    return {
        "kind": "direction",
        "base": lambda r: (0, r.randrange(len(OUTWARD))),
        "worse": lambda v, r: (1, r.randrange(len(INWARD))),
        "same": lambda v, r: v,
        "fmt": lambda v: (OUTWARD, INWARD)[v[0]][v[1]],
        "unit": "",
        "label": label,
    }


def _slope() -> dict:
    """Продольный уклон проезда, целые ‰ в пределах норм паспорта М-033 (4–80 ‰)."""
    return {
        "kind": "quantity",
        "base": lambda r: r.randint(15, 60),
        "worse": lambda v, r: v + r.choice((-1, 1)) * r.randint(5, 10),
        "same": lambda v, r: v,
        "fmt": lambda v: f"{v} ‰",
        "unit": "",
        "label": "Продольный уклон проездов",
    }


def _stairs() -> dict:
    """Марш: (проступь, подступенок, число ступеней), мм и шт. Хуже — проступь меньше нормы СП (250 мм)."""
    return {
        "kind": "quantity",
        "base": lambda r: (
            r.choice((300, 310, 320, 330)),
            r.choice((140, 145, 150)),
            r.randint(8, 16),
        ),
        "worse": lambda v, r: (r.choice((220, 230, 240)), v[1], v[2]),
        "same": lambda v, r: v,
        "fmt": lambda v: (
            f"проступь {v[0]} мм; подступенок {v[1]} мм; {v[2]} ступеней в марше"
        ),
        "unit": "",
        "label": "Лестничные марши",
    }


def _presence(label: str, yes: str, no: str) -> dict:
    """Мероприятие предусмотрено (0) или исключено (1)."""
    return {
        "kind": "presence",
        "base": lambda r: 0,
        "worse": lambda v, r: 1,
        "same": lambda v, r: v,
        "fmt": lambda v: (yes, no)[v],
        "unit": "",
        "label": label,
    }


def _grounding() -> dict:
    """Контур заземления со счётом заземлителей: главное число строки — счёт (Матрица: «уменьшение» — нарушение)."""
    return {
        "kind": "presence",
        "base": lambda r: r.randint(4, 12),
        "worse": lambda v, r: v - r.randint(2, 3),
        "same": lambda v, r: v,
        "fmt": lambda v: f"предусмотрен, {v} вертикальных заземлителей",
        "unit": "",
        "label": "Контур заземления",
    }


METHODS = ("поэлементная разборка", "ручная разборка", "поэлементная разборка краном")
OTHER_METHODS = ("механизированный демонтаж гидромолотом", "взрывной способ")


def _method() -> dict:
    """Метод демонтажа по словарю паспорта М-091; хуже — метод без родства с методом ПД (CHANGED)."""
    return {
        "kind": "method",
        "base": lambda r: (0, r.randrange(len(METHODS))),
        "worse": lambda v, r: (1, r.randrange(len(OTHER_METHODS))),
        "same": lambda v, r: v,
        "fmt": lambda v: (METHODS, OTHER_METHODS)[v[0]][v[1]],
        "unit": "",
        "label": "Метод демонтажа",
    }


def _pipes() -> dict:
    """Материал стояков бытовой канализации К1 (вид category, семейство pipe_sewer): база — чугун, хуже — ПВХ другой семьи."""
    return {
        "kind": "category",
        "base": lambda r: 0,
        "worse": lambda v, r: 1,
        "same": lambda v, r: v,
        "fmt": lambda v: ("чугун", "ПВХ")[v],
        "unit": "",
        "label": "Стояки бытовой канализации К1",
    }


FORMS: dict[str, dict] = {
    "M-033": _slope(),
    "M-043": _direction("Двери эвакуационных выходов открываются"),
    "M-048": _stairs(),
    "M-106": _direction("Двери на путях эвакуации открываются"),
    # T-212: presence / method
    "M-053": _presence(
        "Демпферные ленты в сопряжениях перегородок",
        "предусмотрены",
        "не предусмотрены (исключены)",
    ),
    "M-063": _presence(
        "Деформационные швы", "предусмотрены", "не предусмотрены (исключены)"
    ),
    "M-070": _grounding(),
    "M-075": _pipes(),
    "M-091": _method(),
    "M-092": _presence(
        "Защита действующих коммуникаций",
        "предусмотрена",
        "не предусмотрена (исключена)",
    ),
    "M-095": _presence(
        "Пылеподавление гидроорошением", "предусмотрено", "не предусмотрено (исключено)"
    ),
    "M-122": _presence(
        "Тактильно-контрастные указатели",
        "предусмотрены",
        "не предусмотрены (исключены)",
    ),
}


@cache
def passport_kind(code: str) -> str | None:
    """value.kind паспорта параметра или None, если паспорта нет."""
    # паспорт без цифр замера лежит в passports/draft/ (T-233): формы фабрики строятся и по нему
    for d in ("data/seed/passports", "data/seed/passports/draft"):
        f = F.ROOT / d / f"{code}.json"
        if f.exists():
            return json.loads(f.read_text("utf-8"))["value"]["kind"]
    return None


def form(p: dict) -> dict | None:
    """Генератор паспортной формы параметра Матрицы p в формате пула фабрики — или None (паспорта этого вида нет)."""
    f = FORMS.get(p["code"])
    if f is None or passport_kind(p["code"]) != f["kind"]:
        return None
    return {
        **{k: v for k, v in f.items() if k != "kind"},
        "grp": "V3",
        "needs": p.get("applicability"),
    }
