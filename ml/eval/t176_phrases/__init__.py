"""Наборы фраз T-176 — CMP-05 SUBST (замена марки, материала, типа) и CMP-21 LAYER-SEQ (послойный состав).

Два набора с одним API: `dev.py` — на нём настраиваются паспорта и экстракторы; `holdout.py` — отложенный, написан
отдельно, без знания экстракторов и написаний (aliases) справочника, до доводки. Итоговое качество считается только
на holdout, одним прогоном (урок T-172: подогнанный набор даёт 1,00, отложенный — Recall 0,30). Только вымышленные
объекты, шифры и числа (ADR-0002): ни строки из корпуса и реальных документов.

API модуля набора:

    samples(seed: int, n: int) -> list[dict]   # извлечение: страница → упоминания
    pairs(seed: int, n: int) -> list[dict]     # сравнение: пара «ПД → РД» → метка

n — число примеров на параметр (для pairs — на параметр и на знак метки: n положительных и n отрицательных).
Детерминизм: одинаковые seed и n дают одинаковый набор (random.Random(seed), без глобального random).

Параметры:
    CATEGORY = ["M-050", "M-072", "M-075", "M-079", "M-130"]   # CMP-05, семейства справочника ниже
    LAYERS = ["M-032", "M-044", "M-125", "M-128"]               # CMP-21

Семейство справочника `data/seed/analogs.json` по параметру: M-072 — pipe_pressure, M-075 — pipe_sewer,
M-130 — luminaire, M-050 — finish, M-079 — fan (открытая марка: модель оборудования), M-044, M-125, M-128 —
envelope_layers, M-032 — road_layers. Значение — ключ канона семейства (например "PPR", "INSUL_MW"); у M-079 —
модель как написана в документе.

Позиции (item) и элементы (element) CMP-05:
    M-072: item "В1" (хоз.-питьевой водопровод), "Т3" (горячее водоснабжение), "Т4" (циркуляция ГВС);
           element "main" (магистрали), "riser" (стояки), "branch" (подводки, поквартирная разводка) или None
    M-075: item "К1" (бытовая канализация), "К2" (внутренние водостоки); element "riser", "branch" (отводные
           трубопроводы), "outlet" (выпуски) или None
    M-079: item — марка системы («П1», «В2», «ПВ3», «ВЕ4», «ПД1»…) как написана; element None
    M-050: item None; element "wall", "floor", "ceiling"
    M-130: item None; element None
Позиция не указана в тексте — item None (общее значение стадии).

Пример извлечения (samples):
    {"id": str, "param": str, "kind": "category" | "layers", "lines": [str, ...], "truth": [...]}
    lines — строки текстового слоя одной страницы сверху вниз (ячейки таблицы — через пробелы или «|»), штамп,
    соседние разделы и прочий шум — по желанию автора набора.
    truth у category — все упоминания на странице, которые система обязана найти:
        [{"item": str | None, "element": str | None, "value": str, "alts": [str], "or_analog": bool}]
        alts — другие ключи канона, перечисленные как равноправные варианты («из PP-R или металлополимерных труб»);
        or_analog — после значения стоит «или аналог», «или эквивалент», «или равноценный».
        Пустой список — страница-ловушка: упоминание не должно быть найдено (существующие сети, демонтаж, норма
        «допускается», соседнее здание, другая система — отопление Т1/Т2 для M-072 и т. п.).
    truth у layers — все составы (пироги) на странице:
        [{"item": str | None, "layers": [{"m": str | None, "t": float | None, "t_max": float | None}]}]
        item — марка конструкции как написана («Кр-1», «Тип 1», «НС-2», «П-1») или None; слои — в каноническом
        порядке: сверху вниз (кровля, покрытие, дорожная одежда), снаружи внутрь (стена); если документ перечисляет
        «снизу вверх» или «изнутри наружу» и прямо это пишет, в truth порядок уже развёрнут. m — ключ канона или None
        (материал вне справочника); t — толщина, мм; переменная толщина «50–200 мм» — t=50, t_max=200.

Пара сравнения (pairs):
    {"id": str, "param": str, "kind": "category" | "layers", "pd_lines": [str], "rd_lines": [str],
     "label": "CANDIDATE" | "NEGATIVE_VERIFIED", "mutation": str, "cls": str}
    mutation — вид примера: положительные MUT-07 (замена марки, материала, типа) и MUT-08 (толщина слоя меньше,
    слой удалён, слой переставлен); отрицательные NEG-SAME (то же самое), NEG-SPELL (та же марка в другом написании),
    NEG-SYN (синоним материала), NEG-ANALOG (замена на EQUIVALENT по справочнику), NEG-CHARS («или аналог» в ПД,
    характеристики РД не хуже), NEG-ORDER (перестановка без смысла: другой порядок перечисления с явным «снизу вверх»,
    таблица вместо выноски), NEG-MORE (толщина больше, слой добавлен), NEG-DETAIL (РД уточняет ПД). cls — свободный
    класс случая для разбора ошибок.

Метка CMP-05 (category). Вердикт пары ключей «из ПД → в РД» по семейству справочника:
    1) есть строка analogs с этой парой — её verdict;
    2) иначе у семейства есть derive, оба ключа в одной группе (или derive.any_group) и у обоих заданы все
       характеристики derive — EQUIVALENT, если ни одна не хуже (правило «хуже» ниже), иначе NOT_EQUIVALENT;
    3) иначе UNKNOWN.
    Опорное значение ПД для упоминания РД (item, element): упоминания ПД с тем же item и element → с тем же item и
    element None → с тем же item и любым element (объединение) → item None и element None. Нет опоры — пара не
    сравнивается (не нарушение).
    Упоминание РД — нарушение, если его значение не входит в опору (значения и alts), и:
      • в опоре нет «или аналог» — нарушение, если ни для одного значения опоры вердикт «опора → РД» не EQUIVALENT;
      • в опоре «или аналог» — сравниваются характеристики семейства, а не марка: нарушение, если хоть одна
        характеристика РД хуже характеристики ПД. Значение характеристики стороны — указанное в тексте её упоминания
        («PN 20», «L = 2500 м³/ч», «P = 300 Па», «120 лм/Вт»), иначе — из канона справочника. Характеристика,
        неизвестная хотя бы с одной стороны, не сравнивается; если не сравнилась ни одна — пару не порождать.
    Правило «хуже»: number с better=up — РД < ПД·(1 − tol_rel); better=down — РД > ПД·(1 + tol_rel) (tol_rel по
    умолчанию 0); ordinal — ранг РД ниже ранга ПД на шкале scale (шкала от худшего к лучшему).
    M-079 (открытая марка): модели равны, если совпадают после свёртки — верхний регистр, кириллические двойники
    А В Е К М Н О Р С Т У Х → латиница, без пробелов, дефисов, точек, запятых, скобок и косых черт. Разные модели без
    «или аналог» — нарушение; с «или аналог» — по характеристикам flow и pressure из текста.
    Метка пары CANDIDATE, если нарушение есть хоть у одного упоминания РД, иначе NEGATIVE_VERIFIED.

Метка CMP-21 (layers). Составы ПД и РД сопоставляются по item (одна конструкция без марки на странице — с
единственной конструкцией другой стадии). CANDIDATE, если в любой сопоставленной паре:
      • слой ПД не имеет соответствующего слоя РД (delete_layer);
      • материал слоя заменён, и вердикт «ПД → РД» по справочнику семейства не EQUIVALENT (substitute_material);
      • толщина слоя РД меньше толщины ПД более чем на 0,5 мм (thickness_down; при переменной толщине — по t);
      • слой переставлен — относительный порядок слоёв изменился (reorder).
    NEGATIVE_VERIFIED: то же; другое написание или синоним материала; замена на EQUIVALENT; толщина больше
    (thickness_up); добавлен слой (insert_layer); тот же состав, перечисленный в обратном порядке с явным маркером
    «снизу вверх» / «изнутри наружу»; таблица вместо выноски. Не порождать пар, где у слоя толщина указана только в
    одной стадии или материал слоя вне справочника с обеих сторон и различается.
"""
