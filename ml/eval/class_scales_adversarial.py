def _pick(rng: random.Random, xs: list[str]) -> str:
    return xs[rng.randrange(len(xs))]


def render(code: str, v: str, rng: random.Random, ph: Phraser) -> str:
    """Значение в тексте: формат, шум OCR, марка кабеля."""
    if code == "M-103":
        let, m = v.split()
        s = f"{let}{rng.choice(['', ' ', '-', ' - '])}{m}"
    elif code == "M-015" and v == "I (особая группа)":
        s = rng.choice(["I (особая группа)", "особой группы I"])
    elif code == "M-055" and "," in v and rng.random() < 0.3:
        s = v.replace(",", ".")
    else:
        s = v
    if rng.random() < ph.noise:
        s = _noise(rng, s)
    if code in CABLE_BRAND:
        s = _pick(rng, CABLE_BRAND[code]) + s
    return s


def ocr2_noise(lines: list[str], rng: random.Random) -> list[str]:
    """Шум распознавателя без словаря Tesseract (T-184, PP-OCRv5/VL): пропавший пробел между словами
    («бетонкласса», «классаB30»), пробелы у тире и двоеточий, лишний перенос строки между словами."""
    out: list[str] = []
    for ln in lines:
        ws = ln.split(" ")
        if len(ws) > 2 and rng.random() < 0.5:
            k = rng.randrange(len(ws) - 1)
            ws[k : k + 2] = [ws[k] + ws[k + 1]]
        ln = " ".join(ws)
        if rng.random() < 0.4:
            ln = ln.replace(" – ", "–").replace(": ", ":")
        ws = ln.split(" ")
        if len(ws) > 3 and rng.random() < 0.4:
            k = rng.randrange(1, len(ws) - 1)
            out += [" ".join(ws[:k]), " ".join(ws[k:])]
        else:
            out.append(ln)
    return out


def _wrap(s: str, rng: random.Random) -> str:
    """Перенос строки внутри значения («B3» / «0», «EI 6» / «0»)."""
    if len(s) < 3:
        return s
    k = rng.randrange(1, len(s))
    return s[:k] + "\n" + s[k:]


def phrase(
    code: str,
    v: str,
    els: list[str | None],
    rng: random.Random,
    ph: Phraser,
    marker: str = "",
) -> list[str]:
    """Строки документа с классом v для элементов els (один или два элемента в одной строке)."""
    surf = ph.elements.get(code, {})
    names = [_pick(rng, surf[e]) if e and e in surf else "" for e in els]
    e_text = " и ".join(n for n in names if n)
    val = marker + render(code, v, rng, ph)
    if rng.random() < ph.wrap:
        val = _wrap(val, rng)
    frames = ph.frames + ph.before_frames.get(code, []) * 2
    txt = _pick(rng, frames).format(E=e_text, A=_pick(rng, ph.anchors[code]), V=val)
    lines = [ln.replace(" | ", " | ").strip() for ln in txt.split("\n")]
    return [" ".join(ln.split()) for ln in lines if ln.strip()]


def cases(
    code: str, n: int, rng: random.Random, scales: dict, ph: Phraser
) -> list[dict]:
    pp = json.loads((ROOT / f"data/seed/passports/{code}.json").read_text("utf-8"))
    sp = spec(code, scales)
    scale = scales[pp["value"]["scale_ref"]]["values"]
    down, up, pool = moves(code, scale)
    keys = list(ph.elements.get(code, {}))
    markers = ph.markers.get(code, ph.markers["*"])
    out: list[dict] = []
    seed = 1000

    def groups() -> list[list[str | None]]:
        """Группы элементов: каждая группа — одна строка (два элемента в одной строке — одна группа из двух)."""
        if not keys:
            return [[None]]
        ks = rng.sample(keys, k=min(len(keys), rng.randint(1, 3)))
        if len(ks) >= 2 and rng.random() < ph.pair_line:
            return [ks[:2], *[[k] for k in ks[2:]]]
        return [
            [None] if rng.random() < ph.unlabeled and len(ks) == 1 else [k] for k in ks
        ]

    def pick_down():
        while True:
            a = rng.choice(pool)
            b = down(rng, a)
            if b is not None:
                return a, b

    def distract() -> list[str]:
        ds = ph.distractors.get(code, [])
        return (
            [_pick(rng, ds).format(D=rng.choice(scale))]
            if ds and rng.random() < 0.5
            else []
        )

    def add(label: int, kind: str, docs: list[dict]):
        out.append(
            {
                "schema": SCHEMA,
                "param": code,
                "id": f"{ph.name}:{code}:{kind}:{len(out)}",
                "label": label,
                "kind": kind,
                "docs": docs,
            }
        )

    for i in range(2 * n):
        seed += 3
        label = 1 if i < n else 0
        gs = groups()
        base = {j: rng.choice(pool) for j in range(len(gs))}
        rd = dict(base)
        kind = "MUT-06"
        pd_marker = ["" for _ in gs]
        if label:
            j = rng.randrange(len(gs))
            base[j], rd[j] = pick_down()
        else:
            kind = ["NEG-01", "BETTER", "CONSTRAINT"][i % 3]
            if kind == "BETTER":
                rd = {j: up(rng, v) for j, v in base.items()}
            elif kind == "CONSTRAINT":
                pd_marker = [_pick(rng, markers) for _ in gs]
                rd = {j: up(rng, v) for j, v in base.items()}
        pd_lines = [
            ln
            for j, g in enumerate(gs)
            for ln in phrase(code, base[j], g, rng, ph, pd_marker[j])
        ] + distract()
        rd_lines = [
            ln for j, g in enumerate(gs) for ln in phrase(code, rd[j], g, rng, ph)
        ] + distract()
        rng.shuffle(pd_lines) if len(gs) > 1 and rng.random() < 0.3 else None
        if ph.ocr2 and rng.random() < ph.ocr2:
            pd_lines, rd_lines = ocr2_noise(pd_lines, rng), ocr2_noise(rd_lines, rng)
        add(
            label,
            kind,
            [
                doc(code, sp, "PD", pd_lines, seed),
                doc(code, sp, "RD", rd_lines, seed + 1),
            ],
        )
    return out


SETS = {"dev": DEV, "holdout": HOLDOUT}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--set", choices=list(SETS), required=True)
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--params", default=",".join(W1))
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    scales = json.loads((ROOT / "data/seed/scales.json").read_text("utf-8"))["scales"]
    rng = random.Random(a.seed)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    total = 0
    with a.out.open("w", encoding="utf-8") as f:
        for code in a.params.split(","):
            for c in cases(code, a.n, rng, scales, SETS[a.set]):
                f.write(json.dumps(c, ensure_ascii=False) + "\n")
                total += 1
    print(f"{a.set}: {total} пар → {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
