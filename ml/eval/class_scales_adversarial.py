@dataclass
class Phraser:
    """Шаблонизатор фраз: обороты, рамки, элементы, маркеры ограничения, шум, дистракторы."""

    name: str
    anchors: dict[str, list[str]]
    frames: list[
        str
    ]  # {E} элемент, {A} оборот, {V} значение; «\n» — перенос строки; «|» — ячейки таблицы
    before_frames: dict[
        str, list[str]
    ]  # для параметров, где значение пишут перед оборотом
    elements: dict[str, dict[str, list[str]]]  # код → ключ паспорта → поверхности
    markers: dict[str, list[str]]
    noise: float  # доля значений с OCR-шумом
    wrap: float  # доля значений, разорванных переносом строки
    distractors: dict[str, list[str]]  # {D} — случайное значение шкалы
    pair_line: float = 0.2  # доля «два элемента в одной строке»
    unlabeled: float = 0.2  # доля упоминаний без подписи элемента
    extra: dict[str, list[str]] = field(default_factory=dict)
    ocr2: float = 0.0  # доля пар с шумом второго распознавателя: слитные слова, пробелы у тире, лишние переносы


def _noise(rng: random.Random, v: str) -> str:
    """OCR-шум: кириллица ↔ латиница, 3→З, 0→О, 1→l — по одному искажению."""
    ops = [
        lambda s: s.translate(
            str.maketrans(
                {"А": "A", "В": "B", "С": "C", "Е": "E", "К": "K", "М": "M", "Н": "H"}
            )
        ),
        lambda s: s.translate(
            str.maketrans(
                {"A": "А", "B": "В", "C": "С", "E": "Е", "K": "К", "M": "М", "H": "Н"}
            )
        ),
        lambda s: s.replace("0", "О", 1),
        lambda s: s.replace("3", "З", 1),
        lambda s: s.replace("1", "l", 1),
    ]
    return rng.choice(ops)(v)


