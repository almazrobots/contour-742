// T-259/T-267: deployed UI + real API on an isolated synthetic in-memory DB.
// Every API request is intercepted and handled by buildApp; production is never written.
import {chromium} from 'playwright';
import {readFileSync,writeFileSync,mkdirSync,copyFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const source=process.env.DOCS_API_SOURCE;
const revision='df65e1884788b64ecdec76b73134d9eb75faec2d';
if(!source||readFileSync(join(source,'PINNED-REVISION'),'utf8').trim()!==revision)throw Error('Pinned API source required');
const out=resolve('out/scenario-media');mkdirSync(out,{recursive:true});
const fixture=resolve('out/scenario-fixture');mkdirSync(fixture,{recursive:true,mode:0o700});
process.env.INSPECTOR_DEMO_PASSWORD='docs-synthetic-demo-20260929';
process.env.INSPECTOR_VERIFICATION_CORPUS_DIR=fixture;
process.env.INSPECTOR_PROFILE='dev';
const {openDb}=await import(pathToFileURL(join(source,'apps/api/src/db.ts')));
const {buildApp}=await import(pathToFileURL(join(source,'apps/api/src/app.ts')));
const {ingestAnnotations}=await import(pathToFileURL(join(source,'apps/api/src/services/data-verification.ts')));
const db=await openDb('memory'),app=buildApp(db);await app.ready();
const png=readFileSync('out/synthetic-original.png'),sha=createHash('sha256').update(png).digest('hex');
writeFileSync(join(fixture,sha),png);
const user=await db.get("select id from users where login='curator'");assert.ok(user);
await ingestAnnotations(db,user.id,{id:'docs-synthetic',source_version:'docs-demo.v1',tasks:[{parameter:'M-007',operation:'reading',source_version:'docs-demo.v1',sides:[{sha256:sha,file_name:'Учебный пример — этажность.png',kind:'png',page:1,object_key:'DEMO-01',value:'12',quote:'Количество этажей: 11',stage:'PD',bbox:[0.04,0.25,0.80,0.60]}]}]});
const base='https://127.0.0.1:48845/verification';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:1000},recordVideo:{dir:join(out,'raw'),size:{width:1440,height:1000}}});
const health=await (await context.request.get('https://127.0.0.1:48845/health')).json();assert.equal(health.revision,revision);
const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
let realApiCalls=0;const chapters=[];
await context.route('**/api/**',async route=>{
 const req=route.request(),u=new URL(req.url());const url=u.pathname.replace(/^\/verification(?=\/api\/)/,'')+u.search;
 const r=await app.inject({method:req.method(),url,headers:{...req.headers(),host:'localhost'},...(req.postData()?{payload:req.postData()}: {})});
 realApiCalls++;const headers={...r.headers};delete headers['content-length'];delete headers['transfer-encoding'];
 await route.fulfill({status:r.statusCode,headers,body:r.rawPayload});
});
const start=Date.now();const chapter=(title)=>chapters.push({seconds:(Date.now()-start)/1000,title});
const wait=()=>page.waitForTimeout(3500);
try{
 await page.goto(base+'/#/login');await page.locator('#login').fill('inspector');await page.locator('#password').fill(process.env.INSPECTOR_DEMO_PASSWORD);
 await page.getByRole('button',{name:'Войти',exact:true}).click();await page.getByRole('button',{name:'Получить задание',exact:true}).waitFor();
 chapter('Получите задание в разделе «Разметка данных»');await wait();
 await page.screenshot({path:join(out,'annotation-start.png')});
 await page.getByRole('button',{name:'Получить задание',exact:true}).click();await page.locator('canvas').first().waitFor({state:'visible'});
 await page.waitForFunction(()=>[...document.querySelectorAll('canvas')].every(c=>c.width>0));
 chapter('Сравните предложенное значение 12 с оригиналом: в нём написано 11');await wait();
 await page.screenshot({path:join(out,'annotation-source.png')});
 await page.keyboard.press('2');await page.locator('textarea').fill('В оригинале 11 этажей, система прочитала 12.');
 await page.getByLabel('Правильное значение — если видно').fill('11');
 chapter('Выберите «Нет», добавьте комментарий и правильное значение');await wait();
 await page.screenshot({path:join(out,'annotation-correction.png')});
 await page.getByRole('button',{name:'Сохранить и продолжить',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[data-testid="annotation-saved"]')?.textContent==='1');
 const labels=await db.all('select answer,comment,corrected_value from verification_labels');
 assert.equal(labels.length,1);assert.equal(labels[0].answer,'NO');assert.equal(labels[0].corrected_value,'11');
 chapter('Ответ сохранён настоящим API в отдельной учебной базе');await wait();
 await page.goto(base+'/#/verification-library');await page.getByTestId('library-comment').waitFor();
 assert.match(await page.getByTestId('library-comment').innerText(),/11 этажей/);
 chapter('Откройте «Витрина разметки» и проверьте ответ, комментарий и исправление');await wait();
 await page.screenshot({path:join(out,'library-answer.png')});
 await page.getByRole('button',{name:'☆ Отметить хороший пример',exact:true}).click();await page.getByRole('button',{name:'★ Хороший пример',exact:true}).waitFor();
 await page.getByRole('button',{name:'Хорошие примеры',exact:true}).click();await page.getByTestId('library-comment').waitFor();
 chapter('Отметьте хороший пример и найдите его в личном отборе');await wait();
 await page.screenshot({path:join(out,'library-starred.png')});
 assert.deepEqual(errors,[]);
 const video=page.video();await context.close();const raw=await video.path();
 const duration=(Date.now()-start)/1000;
 const stamp=t=>{const ms=Math.round(t*1000);return `${String(Math.floor(ms/3600000)).padStart(2,'0')}:${String(Math.floor(ms/60000)%60).padStart(2,'0')}:${String(Math.floor(ms/1000)%60).padStart(2,'0')}.${String(ms%1000).padStart(3,'0')}`};
 writeFileSync(join(out,'annotation-walkthrough.vtt'),'WEBVTT\n\n'+chapters.map((c,i)=>`${i+1}\n${stamp(c.seconds)} --> ${stamp(chapters[i+1]?.seconds??duration)}\n${c.title}\n`).join('\n'));
 copyFileSync(raw,join(out,'annotation-walkthrough.webm'));
 writeFileSync(join(out,'provenance.json'),JSON.stringify({schema:'docs-scenario.v1',scenario:'annotation-correction-library',ui_revision:revision,api_revision:revision,environment:'Deployed UI static assets; pinned real API with isolated PGlite memory DB',data:'synthetic only',production_api_calls:0,fixture_api_calls:realApiCalls,labels_persisted:labels.length,validated:['NO','corrected_value','comment','library','starred_filter'],duration_seconds:duration,chapters,page_errors:errors,recorded_at:new Date().toISOString()},null,2)+'\n');
 console.log(JSON.stringify({captured:true,synthetic:true,production_writes:0,real_fixture_labels:labels.length,seconds:duration}));
}finally{await browser.close();await app.close();await db.close();}
